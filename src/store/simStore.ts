import { create } from 'zustand'
import { computeKpis, type Kpis } from '../sim/kpis'
import { DEFAULT_FOCUS, EXPERIMENTS, type ExperimentId } from '../sim/experiments'
import {
  applyEvent, cloneSnapshot, DEFAULT_MOVEMENT, eventIndexAt, runMovementSim, snapshotAt,
  type InventorySnapshot, type MovementConfig, type MovementResult,
} from '../sim/movementSim'

export type Speed = 1 | 2 | 5 | 10

/**
 * The simulation clock. It is a plain mutable object, not React state: the 3D scene reads it every
 * frame, and the UI polls it. Simulation time only advances while running; playback speed scales
 * how fast it advances and never changes what happens at a given simulation time.
 */
export const simClock = { t: 0 }

export interface Scenario {
  id: string
  name: string
  config: MovementConfig
  /** The baseline cannot be overwritten or deleted. */
  builtIn?: boolean
  /** Experiment the scenario was generated by, for grouping. */
  experiment?: ExperimentId
}

const BASELINE: Scenario = { id: 'baseline', name: 'Baseline (5 racks/h)', config: DEFAULT_MOVEMENT, builtIn: true }
const STORAGE_KEY = 'rack-twin.scenarios.v1'

/** Fill fields a scenario saved by an older build may lack. */
const normalise = (c: Partial<MovementConfig>): MovementConfig => ({ ...DEFAULT_MOVEMENT, ...c, stock: { ...c.stock }, extraKanbanPns: [...(c.extraKanbanPns ?? [])] })

function loadSaved(): Scenario[] {
  try {
    const raw = JSON.parse(localStorage.getItem(STORAGE_KEY) ?? '[]') as Scenario[]
    return raw.filter((s) => s && s.id && s.name && s.config).map((s) => ({ ...s, config: normalise(s.config) }))
  } catch {
    return []
  }
}

function persist(scenarios: Scenario[]) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(scenarios.filter((s) => !s.builtIn)))
  } catch { /* storage unavailable: scenarios last for this session only */ }
}

/** Key-order-independent JSON, so equal settings always share a cache entry. */
function stable(v: unknown): string {
  if (Array.isArray(v)) return `[${v.map(stable).join(',')}]`
  if (v && typeof v === 'object') return `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${stable((v as Record<string, unknown>)[k])}`).join(',')}}`
  return JSON.stringify(v)
}
export const configKey = (c: MovementConfig) => stable(c)
export const sameConfig = (a: MovementConfig, b: MovementConfig) => configKey(a) === configKey(b)

// KPIs per configuration, shared by every scenario with identical settings.
const kpiCache = new Map<string, Kpis>()
export function kpisFor(config: MovementConfig, result?: MovementResult): Kpis {
  const key = configKey(config)
  let k = kpiCache.get(key)
  if (!k) {
    k = computeKpis(result ?? runMovementSim(config))
    kpiCache.set(key, k)
  }
  return k
}
export const cachedKpis = (config: MovementConfig) => kpiCache.get(configKey(config))

let nextId = Date.now()
const newId = () => `s${(nextId++).toString(36)}`

interface SimState {
  /** Configuration of the run on screen. */
  config: MovementConfig
  /** Settings being edited; applied with applyDraft. */
  draft: MovementConfig
  result: MovementResult
  error: string | null
  scenarios: Scenario[]
  activeId: string
  /** Parts experiments B and E act on. */
  focus: string[]
  /** Scenarios in the comparison, in selection order; each keeps its colour slot while selected. */
  compare: { id: string; slot: number }[]
  running: boolean
  speed: Speed
  /** Inventory as of the current clock, rebuilt only when an inventory event is crossed. */
  snapshot: InventorySnapshot
  eventIndex: number
  play: () => void
  pause: () => void
  setSpeed: (s: Speed) => void
  reset: () => void
  /** Advance the clock by a real-time delta (seconds). Called once per rendered frame. */
  tick: (dt: number) => void
  seek: (t: number) => void
  setDraft: (patch: Partial<MovementConfig>) => void
  revertDraft: () => void
  applyDraft: () => void
  loadScenario: (id: string) => void
  saveScenario: () => void
  saveAs: (name: string) => void
  duplicate: (id: string) => void
  rename: (id: string, name: string) => void
  remove: (id: string) => void
  addExperiment: (id: ExperimentId) => string[]
  setFocus: (pns: string[]) => void
  toggleCompare: (id: string) => void
}

export const MAX_COMPARE = 4

export const useSim = create<SimState>((set, get) => {
  const result = runMovementSim(DEFAULT_MOVEMENT)

  const sync = () => {
    const { result, eventIndex, snapshot } = get()
    const idx = eventIndexAt(result.inventory, simClock.t)
    if (idx === eventIndex) return
    if (idx > eventIndex) {
      const next = cloneSnapshot(snapshot)
      for (let i = eventIndex; i < idx; i++) applyEvent(next, result.inventory[i])
      set({ snapshot: next, eventIndex: idx })
    } else {
      set({ snapshot: snapshotAt(result, simClock.t), eventIndex: idx })
    }
  }

  /** Run a configuration and put it on screen from t = 0. */
  const show = (config: MovementConfig, activeId = get().activeId) => {
    let result: MovementResult
    try {
      result = runMovementSim(config)
    } catch (e) {
      set({ error: e instanceof Error ? e.message : String(e) })
      return
    }
    kpisFor(config, result)
    simClock.t = 0
    set({ config, draft: config, result, activeId, error: null, running: false, snapshot: snapshotAt(result, 0), eventIndex: eventIndexAt(result.inventory, 0) })
  }

  const putScenarios = (scenarios: Scenario[]) => {
    persist(scenarios)
    set({ scenarios })
  }

  return {
    config: DEFAULT_MOVEMENT,
    draft: DEFAULT_MOVEMENT,
    result,
    error: null,
    scenarios: [BASELINE, ...loadSaved()],
    activeId: BASELINE.id,
    focus: DEFAULT_FOCUS,
    compare: [{ id: BASELINE.id, slot: 0 }],
    running: false,
    speed: 1,
    snapshot: snapshotAt(result, 0),
    eventIndex: eventIndexAt(result.inventory, 0),
    play: () => {
      if (simClock.t >= get().result.horizon) simClock.t = 0
      set({ running: true })
    },
    pause: () => set({ running: false }),
    setSpeed: (speed) => set({ speed }),
    reset: () => {
      simClock.t = 0
      set({ running: false })
      sync()
    },
    tick: (dt) => {
      const { running, speed, result } = get()
      if (!running) return
      // Cap the step so a backgrounded tab doesn't leap ahead when it becomes visible again.
      simClock.t = Math.min(simClock.t + Math.min(dt, 0.1) * speed, result.horizon)
      if (simClock.t >= result.horizon) set({ running: false })
      sync()
    },
    seek: (t) => {
      simClock.t = Math.max(0, Math.min(t, get().result.horizon))
      sync()
    },
    setDraft: (patch) => set((s) => ({ draft: { ...s.draft, ...patch }, error: null })),
    revertDraft: () => set((s) => ({ draft: s.config, error: null })),
    applyDraft: () => show(get().draft),
    loadScenario: (id) => {
      const sc = get().scenarios.find((s) => s.id === id)
      if (sc) show(sc.config, id)
    },
    saveScenario: () => {
      const { scenarios, activeId, config } = get()
      const sc = scenarios.find((s) => s.id === activeId)
      if (!sc || sc.builtIn) return get().saveAs(`Scenario ${scenarios.length}`)
      putScenarios(scenarios.map((s) => (s.id === activeId ? { ...s, config } : s)))
    },
    saveAs: (name) => {
      const sc: Scenario = { id: newId(), name, config: get().config }
      putScenarios([...get().scenarios, sc])
      set({ activeId: sc.id })
    },
    duplicate: (id) => {
      const src = get().scenarios.find((s) => s.id === id)
      if (!src) return
      const copy: Scenario = { id: newId(), name: `${src.name} (copy)`, config: src.config }
      const list = [...get().scenarios]
      list.splice(list.indexOf(src) + 1, 0, copy)
      putScenarios(list)
    },
    rename: (id, name) => putScenarios(get().scenarios.map((s) => (s.id === id && !s.builtIn ? { ...s, name } : s))),
    remove: (id) => {
      const { scenarios, activeId } = get()
      if (scenarios.find((s) => s.id === id)?.builtIn) return
      putScenarios(scenarios.filter((s) => s.id !== id))
      set((s) => ({ compare: s.compare.filter((c) => c.id !== id) }))
      if (activeId === id) set({ activeId: BASELINE.id })
    },
    addExperiment: (id) => {
      const def = EXPERIMENTS.find((e) => e.id === id)!
      const { config, focus, scenarios } = get()
      // Re-running an experiment replaces its previous set.
      const kept = scenarios.filter((s) => s.experiment !== id)
      const added = def.variants(config, focus).map((v) => ({ id: newId(), name: `${id} · ${v.name}`, config: v.config, experiment: id }))
      putScenarios([...kept, ...added])
      set((st) => ({ compare: st.compare.filter((c) => kept.some((k) => k.id === c.id)) }))
      return added.map((s) => s.id)
    },
    setFocus: (focus) => set({ focus }),
    toggleCompare: (id) => set((s) => {
      if (s.compare.some((c) => c.id === id)) return { compare: s.compare.filter((c) => c.id !== id) }
      if (s.compare.length >= MAX_COMPARE) return {}
      const used = new Set(s.compare.map((c) => c.slot))
      const slot = [0, 1, 2, 3].find((n) => !used.has(n))!
      return { compare: [...s.compare, { id, slot }] }
    }),
  }
})

export function formatClock(t: number): string {
  const s = Math.floor(t)
  const h = Math.floor(s / 3600)
  const m = Math.floor((s % 3600) / 60)
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`
}
